"""Classical code constructions with KNOWN parameters.

These exist so the checker can be validated against parameters that are
theorems in the literature (Hamming: d=3; Reed-Solomon: MDS, d=n-k+1;
ternary Golay: [11,6,5] / [12,6,6]), not merely against itself.  The test
suite additionally cross-checks the Brouwer-Zimmermann method against
brute force on the smaller examples, so no expected value rests on a
single code path.
"""
from __future__ import annotations

from itertools import product

from .field import GF
from .matrix import Matrix, nullspace_basis


def hamming_generator(F: GF, r: int) -> Matrix:
    """Generator matrix of the q-ary Hamming code with redundancy r:
    [ (q^r-1)/(q-1), (q^r-1)/(q-1) - r, 3 ]  (KNOWN: d=3 for r >= 2)."""
    if r < 2:
        raise ValueError("Hamming codes need r >= 2")
    cols = []
    for vec in product(F.elements(), repeat=r):
        if all(a == 0 for a in vec):
            continue
        first = next(a for a in vec if a != 0)
        if first == 1:  # one representative per 1-dim subspace
            cols.append(vec)
    H = [[cols[j][i] for j in range(len(cols))] for i in range(r)]
    return nullspace_basis(H, F)


def reed_solomon_generator(F: GF, n: int, k: int, points=None) -> Matrix:
    """[n,k,n-k+1] Reed-Solomon code (KNOWN: MDS) by evaluating all
    polynomials of degree < k at n distinct points of GF(q)."""
    if not 1 <= k <= n <= F.q:
        raise ValueError("need 1 <= k <= n <= q for this RS construction")
    pts = list(points) if points is not None else F.elements()[:n]
    if len(set(pts)) != n:
        raise ValueError("evaluation points must be distinct")
    return [[F.pow(x, i) for x in pts] for i in range(k)]


def repetition_generator(F: GF, n: int) -> Matrix:
    """[n,1,n] repetition code."""
    return [[1] * n]


def single_parity_generator(F: GF, n: int) -> Matrix:
    """[n,n-1,2] single-parity-check code (n >= 2)."""
    if n < 2:
        raise ValueError("need n >= 2")
    rows = []
    for i in range(n - 1):
        row = [0] * n
        row[i] = 1
        row[n - 1] = F.neg(1)
        rows.append(row)
    return rows


# Ternary Golay code: cyclic [11,6,5] code over GF(3) generated by
# g(x) = x^5 + x^4 + 2x^3 + x^2 + 2, a degree-5 factor of x^11 - 1 over
# GF(3).  (Its parameters are classical; in this repo the value d=5 was
# also confirmed by exhaustively enumerating all 3^6 codewords of this
# exact matrix with an independent throwaway script, and the committed
# tests re-confirm it by brute force.)  Rows are the cyclic shifts
# x^i g(x), i = 0..5, coefficients low -> high.
_GOLAY_G = [2, 0, 1, 2, 1, 1]


def ternary_golay_generator(extended: bool = False) -> Matrix:
    """[11,6,5] ternary Golay generator; with ``extended=True`` an overall
    parity coordinate is appended giving the [12,6,6] extended code."""
    rows = []
    for i in range(6):
        row = [0] * i + list(_GOLAY_G) + [0] * (11 - i - len(_GOLAY_G))
        if extended:
            F = GF(3)
            row.append(F.neg(sum(row) % 3))
        rows.append(row)
    return rows
